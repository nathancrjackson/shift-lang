import fs from 'fs';
import path from 'path';

const WORKSPACE_DIR = '.';
const SCHEMA_PATH = path.join(WORKSPACE_DIR, 'js_runtime/src/ast_schema.json');
const AST_GO_PATH = path.join(WORKSPACE_DIR, 'go_runtime/pkg/ast/ast.go');
const UNMARSHAL_GO_PATH = path.join(WORKSPACE_DIR, 'go_runtime/pkg/ast/unmarshal.go');
const DOCS_PATH = path.join(WORKSPACE_DIR, 'docs/6_ast_specification.md');

// Load schema
const schema = JSON.parse(fs.readFileSync(SCHEMA_PATH, 'utf8'));
const definitions = schema.definitions;

// Helper to check if a definition is a statement or expression
const statementTypes = [...definitions.Statement.oneOf.map(x => x.$ref.split('/').pop()), 'Block'];
const expressionTypes = definitions.Expression.oneOf.map(x => x.$ref.split('/').pop());

function getGoType(propSchema, parentName, propName) {
    if (propSchema.$ref) {
        const refName = propSchema.$ref.split('/').pop();
        if (refName === 'Statement' || refName === 'Expression') {
            return refName;
        }
        if (refName === 'Block' || refName === 'IndexExpression' || refName === parentName) {
            return '*' + refName;
        }
        if (refName === 'TypeAnnotation') {
            return 'TypeAnnotation';
        }
        return '*' + refName; // fallback for other concrete structs
    }

    if (propSchema.oneOf) {
        const nonNulls = propSchema.oneOf.filter(x => x.type !== 'null');
        if (nonNulls.length === 1) {
            const innerType = getGoType(nonNulls[0], parentName, propName);
            // Block inside TryStatement reviewBlock should be *Block
            if (nonNulls[0].$ref && nonNulls[0].$ref.split('/').pop() === 'Block' && !innerType.startsWith('*')) {
                return '*' + innerType;
            }
            return innerType;
        }
        // Check if all non-nulls are statements or expressions
        const refNames = nonNulls.map(x => x.$ref ? x.$ref.split('/').pop() : null);
        if (refNames.every(name => name && statementTypes.includes(name))) {
            return 'Statement';
        }
        if (refNames.every(name => name && expressionTypes.includes(name))) {
            return 'Expression';
        }
        return 'any';
    }

    if (propSchema.type === 'array') {
        const items = propSchema.items;
        if (items.$ref) {
            const refName = items.$ref.split('/').pop();
            return '[]' + refName;
        }
        // Handle inline helper structs
        if (parentName === 'StructDeclaration' && propName === 'fields') {
            return '[]StructField';
        }
        if (parentName === 'FunctionDeclaration' && propName === 'params') {
            return '[]Parameter';
        }
        if ((parentName === 'MapLiteral' || parentName === 'StructLiteral') && propName === 'entries') {
            return '[]MapEntry';
        }
        return '[]any';
    }

    if (Array.isArray(propSchema.type)) {
        const types = propSchema.type.filter(t => t !== 'null');
        if (types.length === 1) {
            const t = types[0];
            if (t === 'string') return 'string';
            if (t === 'integer') return 'int';
            if (t === 'boolean') return 'bool';
            if (t === 'number') return 'float64';
        }
        return 'any';
    }

    switch (propSchema.type) {
        case 'string': return 'string';
        case 'integer': return 'int';
        case 'boolean': return 'bool';
        case 'number': return 'float64';
        default: return 'any';
    }
}

