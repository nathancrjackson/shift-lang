function generateUnmarshalGo() {
    let code = `// Code generated by js_runtime/utils/generate_ast_assets.mjs; DO NOT EDIT.
// Based on authoritative AST schema in js_runtime/src/ast_schema.json.

package ast

import (
	"bytes"
	"encoding/json"
	"fmt"
)

// StatementWrapper wraps a Statement interface for custom JSON unmarshaling.
type StatementWrapper struct {
	Statement Statement
}

// UnmarshalJSON implements json.Unmarshaler for StatementWrapper.
func (sw *StatementWrapper) UnmarshalJSON(data []byte) error {
	if bytes.Equal(data, []byte("null")) {
		sw.Statement = nil
		return nil
	}

	var typeHelper struct {
		Type string \`json:"type"\`
	}
	if err := json.Unmarshal(data, &typeHelper); err != nil {
		return err
	}

	var stmt Statement
	switch typeHelper.Type {
`;

    for (const name of statementTypes) {
        code += `\tcase "${name}":
		var v ${name}
		if err := json.Unmarshal(data, &v); err != nil {
			return err
		}
		stmt = &v
`;
    }

    code += `\tdefault:
		return fmt.Errorf("unknown statement type: %s", typeHelper.Type)
	}

	sw.Statement = stmt
	return nil
}

// ExpressionWrapper wraps an Expression interface for custom JSON unmarshaling.
type ExpressionWrapper struct {
	Expression Expression
}

// UnmarshalJSON implements json.Unmarshaler for ExpressionWrapper.
func (ew *ExpressionWrapper) UnmarshalJSON(data []byte) error {
	if bytes.Equal(data, []byte("null")) {
		ew.Expression = nil
		return nil
	}

	var typeHelper struct {
		Type string \`json:"type"\`
	}
	if err := json.Unmarshal(data, &typeHelper); err != nil {
		return err
	}

	var expr Expression
	switch typeHelper.Type {
`;

    for (const name of expressionTypes) {
        code += `\tcase "${name}":
		var v ${name}
		if err := json.Unmarshal(data, &v); err != nil {
			return err
		}
		expr = &v
`;
    }

    code += `\tdefault:
		return fmt.Errorf("unknown expression type: %s", typeHelper.Type)
	}

	ew.Expression = expr
	return nil
}
`;

    // Helper to determine if a type requires a custom unmarshaler
    function isInterfaceOrInterfaceList(goType) {
        return goType === 'Statement' || goType === 'Expression' || goType === '[]Statement' || goType === '[]Expression';
    }

    // Custom unmarshalers for concrete structs containing interfaces
    const structNames = Object.keys(definitions).filter(n => n !== 'Node' && n !== 'Statement' && n !== 'Expression' && n !== 'TypeAnnotation');

    // Add inline helpers as they also need unmarshaling if they contain interfaces
    structNames.push('MapEntry');

    for (const name of structNames) {
        // Find properties
        let properties = {};
        if (name === 'MapEntry') {
            properties = {
                key: { $ref: '#/definitions/Expression' },
                value: { $ref: '#/definitions/Expression' }
            };
        } else {
            const def = definitions[name];
            if (def.allOf) {
                const propDef = def.allOf.find(x => x.properties);
                if (propDef) properties = propDef.properties;
            } else if (def.properties) {
                properties = def.properties;
            }
        }

        // Check if we have any fields that are Statement or Expression (or lists of them)
        const wrapperFields = [];
        for (const [propName, propSchema] of Object.entries(properties)) {
            const goType = getGoType(propSchema, name, propName);
            if (isInterfaceOrInterfaceList(goType)) {
                wrapperFields.push({
                    name: propName,
                    camelName: propName.charAt(0).toUpperCase() + propName.slice(1),
                    goType: goType
                });
            }
        }

        if (wrapperFields.length === 0) {
            continue;
        }

        code += `
// UnmarshalJSON implements json.Unmarshaler for ${name}.
func (n *${name}) UnmarshalJSON(data []byte) error {
	type Alias ${name}
	var aux struct {
`;

        for (const field of wrapperFields) {
            const wrapperType = field.goType.replace('Statement', 'StatementWrapper').replace('Expression', 'ExpressionWrapper');
            code += `\t\t${field.camelName} ${wrapperType} \`json:"${field.name}"\`\n`;
        }

        code += `\t\t*Alias\n\t}
	aux.Alias = (*Alias)(n)
	if err := json.Unmarshal(data, &aux); err != nil {
		return err
	}
`;

        for (const field of wrapperFields) {
            if (field.goType.startsWith('[]')) {
                const innerType = field.goType.slice(2); // Statement or Expression
                code += `\tn.${field.camelName} = make([]${innerType}, len(aux.${field.camelName}))
	for i, w := range aux.${field.camelName} {
		n.${field.camelName}[i] = w.${innerType}
	}
`;
            } else {
                code += `\tn.${field.camelName} = aux.${field.camelName}.${field.goType}\n`;
            }
        }

        code += `	return nil\n}\n`;
    }

    // Add Program custom unmarshaler for version checking
    code += `
// UnmarshalJSON implements json.Unmarshaler for Program.
// It verifies that the JSON contains the required "version" field matching "${schema.version}",
// unless IgnoreVersionMismatch is set to true.
func (p *Program) UnmarshalJSON(data []byte) error {
	type Alias Program
	var aux struct {
		*Alias
	}
	aux.Alias = (*Alias)(p)
	if err := json.Unmarshal(data, &aux); err != nil {
		return err
	}

	if !IgnoreVersionMismatch {
		if p.Version == "" {
			return fmt.Errorf("Schema Error: AST is missing version metadata")
		}
		if p.Version != "${schema.version}" {
			return fmt.Errorf("Schema Error: Unsupported AST schema version: '%s'. Expected '${schema.version}'.", p.Version)
		}
	}
	return nil
}
`;

    fs.writeFileSync(UNMARSHAL_GO_PATH, code, 'utf8');
    console.log(`Generated: ${UNMARSHAL_GO_PATH}`);
}

