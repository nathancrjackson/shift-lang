function generateAstGo() {
    let code = `// Code generated by js_runtime/utils/generate_ast_assets.mjs; DO NOT EDIT.
// Based on authoritative AST schema in js_runtime/src/ast_schema.json.

package ast

// IgnoreVersionMismatch controls whether AST unmarshaling validates the schema version.
// If set to true, version checking is bypassed.
var IgnoreVersionMismatch = false

// SchemaVersion defines the authoritative version of the AST schema.
const SchemaVersion = "${schema.version}"

// Node represents the base interface for all nodes in the Shift Abstract Syntax Tree (AST).
type Node interface {
	NodeType() string
	GetStart() int
	GetEnd() int
	GetLine() int
}

// Statement represents an AST node that is a statement.
type Statement interface {
	Node
	stmtNode()
}

// Expression represents an AST node that evaluates to a value.
type Expression interface {
	Node
	exprNode()
}

// BaseNode implements the common positioning fields for all AST nodes.
type BaseNode struct {
	Type  string \`json:"type"\`
	Start int    \`json:"start"\`
	End   int    \`json:"end"\`
	Line  int    \`json:"line"\`
}

// NodeType returns the type name of the node.
func (b *BaseNode) NodeType() string { return b.Type }

// GetStart returns the start character index of the node in the source code.
func (b *BaseNode) GetStart() int    { return b.Start }

// GetEnd returns the end character index of the node in the source code.
func (b *BaseNode) GetEnd() int      { return b.End }

// GetLine returns the source code line number where the node begins.
func (b *BaseNode) GetLine() int     { return b.Line }
`;

    // Add inline helpers
    code += `
// TypeAnnotation represents a type definition or constraint, potentially including generic types.
type TypeAnnotation struct {
	Type    string          \`json:"type"\`
	Name    string          \`json:"name"\`
	Generic *TypeAnnotation \`json:"generic"\`
}

// StructField represents a single field declaration within a Struct.
type StructField struct {
	Name string         \`json:"name"\`
	Type TypeAnnotation \`json:"type"\`
}

// Parameter represents a parameter declaration inside a function signature.
type Parameter struct {
	Type     string         \`json:"type"\` // always "Parameter"
	Name     string         \`json:"name"\`
	DataType TypeAnnotation \`json:"dataType"\`
	Shared   bool           \`json:"shared"\`
}

// MapEntry represents a single key-value mapping within a map.
type MapEntry struct {
	Key   Expression \`json:"key"\`
	Value Expression \`json:"value"\`
}
`;

    // Generate concrete structs
    for (const [name, def] of Object.entries(definitions)) {
        if (name === 'Node' || name === 'Statement' || name === 'Expression' || name === 'TypeAnnotation') {
            continue;
        }

        // Find properties
        let properties = {};
        let embedsBaseNode = false;

        if (def.allOf) {
            embedsBaseNode = def.allOf.some(x => x.$ref === '#/definitions/Node');
            const propDef = def.allOf.find(x => x.properties);
            if (propDef) {
                properties = propDef.properties;
            }
        } else if (def.properties) {
            properties = def.properties;
        }

        code += `\n// ${name} represents the AST node structure for ${name}.\n`;
        code += `type ${name} struct {\n`;
        if (embedsBaseNode) {
            code += `\tBaseNode\n`;
        }



        for (const [propName, propSchema] of Object.entries(properties)) {
            if (propName === 'type' && embedsBaseNode) {
                // inherited from BaseNode
                continue;
            }

            const goType = getGoType(propSchema, name, propName);
            const camelName = propName.charAt(0).toUpperCase() + propName.slice(1);

            // Check if field is optional/nullable
            const isOptional = propSchema.oneOf && propSchema.oneOf.some(x => x.type === 'null');
            const jsonTag = `\`json:"${propName}${isOptional ? ',omitempty' : ''}"\``;

            code += `\t${camelName} ${goType} ${jsonTag}\n`;
        }
        code += `}\n`;
    }

    // Add marker methods for Statement and Expression implementations
    code += `\n// Marker methods for statements\n`;
    for (const name of statementTypes) {
        code += `func (*${name}) stmtNode() {}\n`;
    }

    code += `\n// Marker methods for expressions\n`;
    for (const name of expressionTypes) {
        code += `func (*${name}) exprNode() {}\n`;
    }

    fs.writeFileSync(AST_GO_PATH, code, 'utf8');
    console.log(`Generated: ${AST_GO_PATH}`);
}

